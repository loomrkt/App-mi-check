    private val systemPrompt = """
        Tu es un analyste francophone de captures d'écran et de vidéos. On te fournit une ou plusieurs images (3 images successives si vidéo) et éventuellement le texte OCR.
        Décide : "fake" si le contenu est trompeur, manipulé, généré par IA et présenté comme réel ; "real" s'il est authentique ; "uncertain" si tu ne peux pas trancher.
        RÈGLES :
        - Une photo, capture ou vidéo ordinaire sans anomalie concrète est "real". Ne classe pas "fake" par prudence, à cause de la qualité, de la compression, d'un flou ou d'une retouche légère.
        - "fake" seulement avec un indice observable : anatomie impossible (mains, doigts, dents, oreilles), texte en pseudo-alphabet, logos altérés, ombres/reflets incohérents, perspective impossible, arrière-plan répétitif, bijoux/accessoires fondus, montage visible, ou label IA trompeur.
        - Vérifie les filigranes et labels : Gemini, Google AI, Imagen, Meta AI, DALL-E, ChatGPT, OpenAI, Midjourney, Stable Diffusion, Adobe Firefly, Leonardo, Ideogram, Grok, Copilot, Bing Image Creator, Canva, Playground, Recraft, Krea, Freepik, Flux, Runway, Pika, Sora, Veo, Kling, Hailuo, "Made with AI", "AI generated", pin C2PA. Absence de filigrane ne signifie pas absence d'IA.
        - Vidéo (3 images successives) : compare l'identité, le visage, le fond, le texte, la lumière et la physique entre les images ; signale morphing, scintillement, dérive ou incohérence temporelle.
        - Ignore l'interface de l'application (boutons, likes, commentaires) sauf pour identifier la source du texte et les labels IA.
        - TEXTE : indique la source probable (Facebook, Instagram, WhatsApp, TikTok, article web, document, publicité, écran d'application). Si l'OCR est absent, mets "present": false et claims vide.
        - N'invente pas de faits ou d'URL. Si tu disposes de l'outil de recherche web, tu peux vérifier les affirmations ; ne cite que des sources réellement consultées.
        - Confiance : 60 à 85 pour un cas typique, plus de 90 seulement avec une preuve forte.
        Réponds UNIQUEMENT avec un objet JSON valide, sans texte autour:
        {"verdict":"fake|real|uncertain","confidence":0,"summary":"une phrase de 120 caractères maximum","reasons":["2 raisons courtes de 80 caractères maximum"],"media":"image|video","text":{"present":true,"source":"ex: Post Facebook","verdict":"fake|real|uncertain","claims":[{"claim":"70 caractères max","assessment":"70 caractères max"}]},"image":{"verdict":"fake|real|uncertain","ai_generated":true,"manipulated":false,"watermark":{"present":true,"name":"Gemini","location":"bas droite"},"signals":["2 signaux de 80 caractères maximum"]}}
        Réponds en français, très brièvement.
    """.trimIndent()

    data class Claim(val claim: String, val assessment: String)

    data class Analysis(
        val verdict: String,
        val confidence: Int,
        val summary: String,
        val reasons: List<String>,
        val media: String,
        val textPresent: Boolean,
        val textSource: String,
        val textVerdict: String,
        val claims: List<Claim>,
        val imageVerdict: String,
        val aiGenerated: Boolean,
        val manipulated: Boolean,
        val watermarkPresent: Boolean,
        val watermarkName: String,
        val watermarkLocation: String,
        val imageSignals: List<String>,
        val sources: List<String>
    )

    class AnalysisException(message: String) : Exception(message)

    fun analyze(
        apiKey: String,
        imagesBase64: List<String>,
        ocrText: String,
        isVideo: Boolean
    ): Analysis {
        val normalizedOcr = normalizeOcr(ocrText)
        return try {
            request(
                apiKey = apiKey,
                imagesBase64 = imagesBase64,
                normalizedOcr = normalizedOcr,
                isVideo = isVideo,
                useWebSearch = normalizedOcr.isNotEmpty()
            )
        } catch (error: AnalysisException) {
            if (normalizedOcr.isNotEmpty() && isRetryableWithoutSearch(error.message.orEmpty())) {
                request(
                    apiKey = apiKey,
                    imagesBase64 = imagesBase64,
                    normalizedOcr = normalizedOcr,
                    isVideo = isVideo,
                    useWebSearch = false
                )
            } else {
                throw error
            }
        }
    }

    private fun request(
        apiKey: String,
        imagesBase64: List<String>,
        normalizedOcr: String,
        isVideo: Boolean,
        useWebSearch: Boolean
    ): Analysis {
        val dateLabel = SimpleDateFormat("d MMMM yyyy", Locale.FRENCH).format(Date())
        val hint = watermarkHint(normalizedOcr)
        val frameLine = if (isVideo) {
            "Ces ${imagesBase64.size} images sont des captures successives (environ 0,7 s d'écart) d'une vidéo."
        } else {
            "Cette image est une capture d'écran."
        }
        val userPrompt = buildString {
            appendLine("Date du jour : $dateLabel")
            appendLine(frameLine)
            if (normalizedOcr.isEmpty()) {
                appendLine("Aucun texte détecté par l'OCR. Mets \"text.present\": false et claims vide.")
            } else {
                appendLine("Texte OCR détecté (brut, ordre de lecture ; peut contenir l'interface de l'application) :")
                appendLine(normalizedOcr)
                if (useWebSearch) {
                    appendLine("Tu peux vérifier les affirmations par recherche web. Ne cite que des sources réellement consultées.")
                }
            }
            if (hint.isNotEmpty()) {
                appendLine("Indice filigrane/outil trouvé dans l'OCR : $hint")
            }
            appendLine("Réponds UNIQUEMENT avec le JSON demandé, sans texte avant ni après, sans balises Markdown.")
        }.trim()

        val userContent = JSONArray()
            .put(JSONObject().put("type", "text").put("text", userPrompt))
        imagesBase64.take(3).forEach { image ->
            userContent.put(
                JSONObject().put("type", "image_url").put(
                    "image_url",
                    JSONObject()
                        .put("url", "data:image/jpeg;base64,$image")
                        .put("detail", "high")
                )
            )
        }

        val payload = JSONObject()
            .put("model", MODEL)
            .put("temperature", 0.2)
            .put("max_tokens", 600)
            .put("thinking", JSONObject().put("type", "disabled"))
            .put(
                "messages",
                JSONArray()
                    .put(JSONObject().put("role", "system").put("content", systemPrompt))
                    .put(JSONObject().put("role", "user").put("content", userContent))
            )
        if (useWebSearch) {
            payload.put(
                "tools",
                JSONArray().put(JSONObject().put("type", "deepseek_web_search"))
            )
        } else {
            payload.put("response_format", JSONObject().put("type", "json_object"))
        }

        val responseBody = post(
            apiKey,
            payload.toString(),
            if (useWebSearch) 90000 else 60000
        )
        val message = JSONObject(responseBody)
            .optJSONArray("choices")
            ?.optJSONObject(0)
            ?.optJSONObject("message")
            ?: throw AnalysisException("Réponse vide du service d'analyse.")
        val content = message.optString("content")
        if (content.isBlank()) {
            throw AnalysisException("Réponse vide du service d'analyse.")
        }
        val parsed = parse(content) ?: throw AnalysisException("Le service a renvoyé une réponse illisible.")
        val sources = if (useWebSearch) extractSourceDomains(message) else emptyList()
        return parsed.copy(
            media = if (isVideo) "video" else "image",
            sources = sources
        )
    }

    private fun isRetryableWithoutSearch(message: String): Boolean {
        return !message.contains("Clé API") &&
            !message.contains("Crédit") &&
            !message.contains("Trop de requêtes")
    }

    fun extractSourceDomains(message: JSONObject): List<String> {
        val urls = mutableListOf<String>()
        message.optJSONArray("annotations")?.let { annotations ->
            for (index in 0 until annotations.length()) {
                val citation = annotations.optJSONObject(index)?.optJSONObject("url_citation")
                val url = citation?.optString("url").orEmpty()
                if (url.isNotEmpty()) urls.add(url)
            }
        }
        message.optJSONArray("server_tool_calls")?.let { steps ->
            for (stepIndex in 0 until steps.length()) {
                val calls = steps.optJSONObject(stepIndex)?.optJSONArray("calls") ?: continue
                for (callIndex in 0 until calls.length()) {
                    val sources = calls.optJSONObject(callIndex)?.optJSONArray("sources") ?: continue
                    for (sourceIndex in 0 until sources.length()) {
                        val url = sources.optJSONObject(sourceIndex)?.optString("url").orEmpty()
                        if (url.isNotEmpty()) urls.add(url)
                    }
                }
            }
        }
        return urls.mapNotNull { domainOf(it) }.distinct().take(2)
    }

    private fun domainOf(url: String): String? {
        return try {
            val host = URL(url).host ?: return null
            host.lowercase(Locale.ROOT).removePrefix("www.")
        } catch (_: Exception) {
            null
        }
    }

    fun normalizeOcr(raw: String): String {
        val lines = raw.lines()
            .map { it.replace(Regex("\\s+"), " ").trim() }
            .filter { it.isNotEmpty() }
            .distinct()
            .take(40)
        val builder = StringBuilder()
        for (line in lines) {
            val clipped = line.take(160)
            if (builder.length + clipped.length > 1200) break
            if (builder.isNotEmpty()) builder.append('\n')
            builder.append(clipped)
        }
        return builder.toString().trim()
    }

    fun watermarkHint(ocrText: String): String {
        val lower = ocrText.lowercase(Locale.ROOT)
        if (lower.isEmpty()) return ""
        return watermarkKeywords.filter { lower.contains(it) }.joinToString(", ")
    }

    fun parse(raw: String): Analysis? {
        val cleaned = raw.trim()
            .removePrefix("```json")
            .removePrefix("```")
            .removeSuffix("```")
            .trim()
        val json = try {
            JSONObject(cleaned)
        } catch (_: Exception) {
            return null
        }
        val verdict = normalizeVerdict(json.optString("verdict")) ?: return null
        val confidence = readConfidence(json.opt("confidence"))
        val summary = json.optString("summary").trim().take(130)
        val reasons = readStringList(json.optJSONArray("reasons"), 2, 90)
        val media = if (json.optString("media").trim().equals("video", ignoreCase = true)) {
            "video"
        } else {
            "image"
        }

        val textSection = json.optJSONObject("text")
        val textPresent = textSection?.optBoolean("present", false) ?: false
        val textSource = textSection?.optString("source").orEmpty().trim().take(40)
        val textVerdict = normalizeVerdict(textSection?.optString("verdict").orEmpty()) ?: "uncertain"
        val claims = mutableListOf<Claim>()
        if (textPresent) {
            val claimsArray = textSection?.optJSONArray("claims")
            if (claimsArray != null) {
                for (index in 0 until minOf(claimsArray.length(), 1)) {
                    val item = claimsArray.optJSONObject(index) ?: continue
                    val claim = item.optString("claim").trim().take(80)
                    if (claim.isEmpty()) continue
                    claims.add(Claim(claim, item.optString("assessment").trim().take(80)))
                }
            }
        }

        val imageSection = json.optJSONObject("image")
        val imageVerdict = normalizeVerdict(imageSection?.optString("verdict").orEmpty()) ?: "uncertain"
        val aiGenerated = imageSection?.optBoolean("ai_generated", false) ?: false
        val manipulated = imageSection?.optBoolean("manipulated", false) ?: false
        val watermark = imageSection?.optJSONObject("watermark")
        val watermarkPresent = watermark?.optBoolean("present", false) ?: false
        val watermarkName = if (watermarkPresent) {
            watermark?.optString("name").orEmpty().trim().take(30)
        } else {
            ""
        }
        val watermarkLocation = if (watermarkPresent) {
            watermark?.optString("location").orEmpty().trim().take(25)
        } else {
            ""
        }
        val imageSignals = readStringList(imageSection?.optJSONArray("signals"), 2, 90)

        return Analysis(
            verdict = verdict,
            confidence = confidence,
            summary = summary,
            reasons = reasons,
            media = media,
            textPresent = textPresent,
            textSource = textSource,
            textVerdict = textVerdict,
            claims = claims,
            imageVerdict = imageVerdict,
            aiGenerated = aiGenerated,
            manipulated = manipulated,
            watermarkPresent = watermarkPresent,
            watermarkName = watermarkName,
            watermarkLocation = watermarkLocation,
            imageSignals = imageSignals,
            sources = emptyList()
        )
    }

    private fun post(apiKey: String, payload: String, readTimeoutMs: Int): String {
        var connection: HttpURLConnection? = null
        try {
            connection = URL(API_URL).openConnection() as HttpURLConnection
            connection.requestMethod = "POST"
            connection.connectTimeout = 15000
            connection.readTimeout = readTimeoutMs
            connection.doOutput = true
            connection.setRequestProperty("Content-Type", "application/json; charset=utf-8")
            connection.setRequestProperty("Authorization", "Bearer $apiKey")
            connection.outputStream.use { it.write(payload.toByteArray(Charsets.UTF_8)) }

            val code = connection.responseCode
            val stream = if (code in 200..299) connection.inputStream else connection.errorStream
            val body = stream?.bufferedReader(Charsets.UTF_8)?.use { it.readText() }.orEmpty()
            if (code !in 200..299) {
                throw AnalysisException(mapError(code))
            }
            return body
        } catch (error: AnalysisException) {
            throw error
        } catch (_: IOException) {
            throw AnalysisException("Connexion impossible. Vérifiez votre réseau.")
        } catch (_: Exception) {
            throw AnalysisException("Erreur du service d'analyse.")
        } finally {
            connection?.disconnect()
        }
    }

    private fun mapError(code: Int): String = when (code) {
        401, 403 -> "Clé API invalide ou refusée."
        402 -> "Crédit DeepSeek insuffisant."
        429 -> "Trop de requêtes. Réessayez dans un instant."
        500, 502, 503, 504 -> "Service d'analyse indisponible."
        else -> "Erreur du service d'analyse (code $code)."
    }

    private fun readConfidence(value: Any?): Int {
        val number = when (value) {
            is Number -> value.toInt()
            is String -> Regex("\\d{1,3}").find(value)?.value?.toIntOrNull() ?: 0
            else -> 0
        }
        return number.coerceIn(0, 100)
    }

    private fun readStringList(array: JSONArray?, limit: Int, maxLength: Int): List<String> {
        if (array == null) return emptyList()
        val result = mutableListOf<String>()
        for (index in 0 until minOf(array.length(), limit)) {
            val value = array.optString(index).trim().take(maxLength)
            if (value.isNotEmpty()) result.add(value)
        }
        return result
    }

    private fun normalizeVerdict(value: String): String? {
        val normalized = value.trim().lowercase(Locale.ROOT)
        if (normalized.isEmpty()) return null
        return when {
            normalized.contains("fake") || normalized.contains("faux") ||
                normalized.contains("fausse") || normalized.contains("trompe") ||
                normalized.contains("manipul") || normalized.contains("ia générée") ||
                normalized.contains("ia generee") -> "fake"
            normalized.contains("real") || normalized.contains("réel") ||
                normalized.contains("reel") || normalized.contains("vrai") ||
                normalized.contains("authentique") -> "real"
            normalized.contains("uncertain") || normalized.contains("incertain") ||
                normalized.contains("doute") || normalized.contains("indéterm") ||
                normalized.contains("indeterm") -> "uncertain"
            else -> null
        }
    }
}
